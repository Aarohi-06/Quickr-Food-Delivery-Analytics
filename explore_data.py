r"""Explore Quickr's source CSV without changing or cleaning the dataset.

Run with: .venv\Scripts\python.exe explore_data.py
Only the Markdown report is written. Normalized values below are temporary
diagnostic views used to identify problems, not a cleaned output dataset.
"""

from pathlib import Path
import hashlib
import platform

import pandas as pd


ROOT = Path(__file__).resolve().parent
DATASET = ROOT / "data" / "raw" / "food_delivery.csv"
REPORT = ROOT / "reports" / "dataset_exploration.md"
MISSING_TOKENS = {"", "nan", "null", "none", "na", "n/a", "<na>"}


def fingerprint(path):
    """Check that the source file stays byte-for-byte unchanged."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def block(value):
    """Use plain text tables so no extra Markdown dependency is needed."""
    return "\n```text\n" + str(value) + "\n```\n"


def main():
    if not DATASET.is_file():
        raise FileNotFoundError(f"Dataset not found: {DATASET}")

    before = fingerprint(DATASET)
    # The normal load shows pandas' inferred types and missing-value behavior.
    df = pd.read_csv(DATASET)
    # A second read preserves literal strings, including whitespace and NaN.
    raw = pd.read_csv(DATASET, dtype=str, keep_default_na=False)
    stripped = raw.apply(lambda column: column.str.strip())
    missing = stripped.apply(lambda column: column.str.lower().isin(MISSING_TOKENS))
    # Weather embeds its value after a literal "conditions " prefix.
    if "Weatherconditions" in stripped:
        weather_values = stripped["Weatherconditions"].str.replace(
            r"^conditions\s+", "", regex=True).str.strip().str.lower()
        missing["Weatherconditions"] = missing["Weatherconditions"] | weather_values.isin(MISSING_TOKENS)
    whitespace = raw.ne(stripped).sum()
    numeric_columns = df.select_dtypes(include="number").columns.tolist()
    categorical_columns = df.select_dtypes(exclude="number").columns.tolist()

    missing_summary = pd.DataFrame({
        "pandas_missing": df.isna().sum(),
        "empty_or_whitespace": stripped.eq("").sum(),
        "text_placeholders": missing.sum() - stripped.eq("").sum(),
        "total_missing_including_placeholders": missing.sum(),
        "missing_percent": (missing.mean() * 100).round(2),
        "values_with_outer_whitespace": whitespace,
    })

    sections = [
        "# Quickr — Dataset Exploration\n",
        f"Source: `{DATASET.relative_to(ROOT).as_posix()}`. "
        f"Python {platform.python_version()}; pandas {pd.__version__}.\n",
        "This report is generated by `explore_data.py`. No cleaning is performed. "
        "All normalization and parsing below are temporary diagnostic checks.\n",
        "## Dataset size\n",
        f"- Rows: **{len(df):,}**\n- Columns: **{len(df.columns)}**\n"
        f"- Source size: {DATASET.stat().st_size:,} bytes\n",
        "## Column names and inferred data types\n",
        block(df.dtypes.to_string()),
        "## First five records (literal source values)\n",
        block(raw.head().to_string(index=False)),
        "## Missing values and whitespace\n",
        "Missing tokens are matched case-insensitively after trimming whitespace: "
        + ", ".join(repr(token) for token in sorted(MISSING_TOKENS)) + ". "
        "Weather is also checked after removing its literal `conditions ` prefix, "
        "so `conditions NaN` counts as missing. Empty strings and text placeholders "
        "are separate, non-overlapping counts.\n",
        block(missing_summary.to_string()),
    ]
    for column in raw.columns:
        counts = raw.loc[missing[column], column].value_counts(dropna=False)
        if not counts.empty:
            sections.append(f"Literal missing representations in `{column}`: "
                            + ", ".join(f"{value!r}: {count}" for value, count in counts.items()) + "\n")

    sections += [
        "## Duplicate records\n",
        f"- Exact duplicate rows beyond the first occurrence: {int(raw.duplicated().sum()):,}\n"
        f"- Duplicate rows after diagnostic whitespace trimming: {int(stripped.duplicated().sum()):,}\n",
        "## Numerical and categorical columns\n",
        "Pandas-inferred numerical columns: " + ", ".join(f"`{c}`" for c in numeric_columns) + ".\n",
        "Pandas-inferred non-numerical columns (including IDs, dates, times and target): "
        + ", ".join(f"`{c}`" for c in categorical_columns) + ".\n",
        "Columns stored as text may still represent numbers; see the diagnostic parsing below.\n",
        "## Basic descriptive statistics\n",
        block(df.describe(include="all").to_string()),
        "## Categorical values and frequencies\n",
        "These counts use temporary whitespace-trimmed values; missing tokens are excluded. "
        "High-cardinality columns show only their ten most common values.\n",
    ]
    for column in categorical_columns:
        values = stripped.loc[~missing[column], column]
        sections += [f"### {column}\nNonmissing distinct values: {values.nunique():,}\n",
                     block(values.value_counts().head(10).to_string())]

    sections.append("## Target variable: Time_taken(min)\n")
    target = "Time_taken(min)"
    if target not in raw:
        sections.append("ERROR: expected target column is absent.\n")
    else:
        # Extract minutes only for exploration; never assign back to the source.
        minutes = pd.to_numeric(stripped[target].str.extract(
            r"^\(min\)\s*(\d+(?:\.\d+)?)$", expand=False), errors="coerce")
        invalid = ~missing[target] & minutes.isna()
        sections += [
            f"Stored dtype: `{df[target].dtype}`. Expected literal format: `(min) 24`.\n"
            f"Missing targets: {int(missing[target].sum())}; matching format: {int(minutes.notna().sum())}; "
            f"nonmissing format failures: {int(invalid.sum())}; "
            f"nonpositive parsed values: {int(minutes.le(0).sum())}.\n",
            "Source examples: " + ", ".join(repr(v) for v in raw[target].head()) + ".\n",
            block(minutes.describe().to_string()),
        ]
        if invalid.any():
            sections.append(block(raw.loc[invalid, target].value_counts().head(10).to_string()))

    sections.append("## Potential data-quality problems\n")
    sections.append(f"- Cells with leading/trailing whitespace: {int(whitespace.sum()):,}.\n")
    if "ID" in raw:
        sections.append(f"- Duplicate nonmissing order IDs beyond the first: "
                        f"{int(stripped.loc[~missing['ID'], 'ID'].duplicated().sum())}.\n")
    for column in ["Delivery_person_Age", "Delivery_person_Ratings", "multiple_deliveries"]:
        if column in raw:
            parsed = pd.to_numeric(stripped[column].mask(missing[column]), errors="coerce")
            failures = ~missing[column] & parsed.isna()
            sections.append(f"- `{column}`: {int(parsed.notna().sum()):,} parseable numbers; "
                            f"{int(failures.sum())} nonmissing numeric parsing failures.\n")
            sections.append(block(parsed.describe().to_string()))
            if column == "Delivery_person_Age":
                sections.append(f"  Ages below 18 or above 80: {int(((parsed < 18) | (parsed > 80)).sum())}.\n")
            if column == "Delivery_person_Ratings":
                sections.append(f"  Ratings outside the assumed 0–5 scale: {int(((parsed < 0) | (parsed > 5)).sum())}.\n")
    for column in [c for c in raw if "latitude" in c or "longitude" in c]:
        numbers = pd.to_numeric(stripped[column], errors="coerce")
        limit = 90 if "latitude" in column else 180
        sections.append(f"- `{column}`: zero coordinates = {int(numbers.eq(0).sum())}; "
                        f"negative coordinates = {int(numbers.lt(0).sum())}; "
                        f"outside legal coordinate range = {int(numbers.abs().gt(limit).sum())}. "
                        "Zero or negative coordinates require contextual review; negative coordinates can be valid.\n")
    for column, date_format in [("Order_Date", "%d-%m-%Y"), ("Time_Orderd", "%H:%M:%S"),
                                ("Time_Order_picked", "%H:%M:%S")]:
        if column in raw:
            parsed = pd.to_datetime(stripped[column].mask(missing[column]), format=date_format, errors="coerce")
            failures = ~missing[column] & parsed.isna()
            sections.append(f"- `{column}`: {int(failures.sum())} nonmissing values fail format `{date_format}`.\n")
            if column == "Order_Date":
                sections.append(f"  Parsed date range: {parsed.min()} to {parsed.max()}.\n")
            if failures.any():
                sections.append(block(stripped.loc[failures, column].value_counts().head(10).to_string()))
    sections += [
        "## Recommended cleaning steps (future phase only)\n",
        "1. Trim surrounding whitespace and map the documented missing placeholders to actual missing values.\n"
        "2. Convert age, ratings and multiple-delivery counts to numeric types; decide how to handle missing values.\n"
        "3. Extract numeric minutes from the target and validate positive values before modeling.\n"
        "4. Parse dates and times after reviewing format failures; account for midnight crossings when deriving durations.\n"
        "5. Review zero coordinates and geographically unexpected locations using source context before correcting or removing rows.\n"
        "6. Review category spelling (including `Metropolitian`) and the weather prefix; standardize labels consistently.\n"
        "   Review flagged ages and ratings against the source definitions before treating them as invalid.\n"
        "7. Review any duplicate rows or order IDs before removal; retain the original source file.\n"
        "8. Treat order/person IDs as identifiers and assess their usefulness and potential leakage separately from predictive features.\n",
    ]
    after = fingerprint(DATASET)
    if before != after:
        raise RuntimeError("The source dataset changed during exploration.")
    sections += ["## Execution and source integrity\n",
                 "Exploration completed successfully. Source SHA-256 was identical before and after execution.\n",
                 f"SHA-256: `{after}`\n",
                 "No cleaned dataset, model, database, or application was created.\n"]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(sections), encoding="utf-8")
    print(f"Dataset: {DATASET}")
    print(f"Rows: {len(df):,}; columns: {len(df.columns)}")
    print(missing_summary.to_string())
    print(f"Exact duplicates: {raw.duplicated().sum()}")
    print(f"Report written: {REPORT}")
    print(f"Source unchanged (SHA-256): {after}")


if __name__ == "__main__":
    main()
